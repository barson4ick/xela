@router.message(Command("hero"))
async def cmd_hero(message: Message) -> None:
    if message.from_user:
        await ensure_user(message.from_user.id, message.chat.id, display_name(message.from_user))
    chat_id = message.chat.id
    today = day_str()

    existing = await get_hero(chat_id, today)
    if existing:
        _, name, title = existing
        await message.reply(f"🌟 Сегодня <b>«{esc(title)}»</b> — <b>{esc(name)}</b>!")
        return

    chosen = await get_random_user(chat_id)
    if not chosen:
        await message.reply("⚠️ В базе чата пока нет участников.")
        return

    user_id, name = chosen
    title = random.choice(HERO_TITLES)
    await set_hero(chat_id, today, user_id, title)
    hero = await get_hero(chat_id, today)  # на случай гонки победит первая запись
    _, name, title = hero
    new_size = await add_size(hero[0], chat_id, name, 1, 'hero')

    await message.reply(
        f"🌟 <b>Герой дня выбран!</b>\n"
        f"Титул <b>«{esc(title)}»</b> достаётся — <b>{esc(name)}</b>!\n"
        f"Бонус: <b>+1 см</b> (теперь {new_size} см)"
    )










@router.message(Command("quote"))
async def cmd_quote(message: Message) -> None:
    chat_id = message.chat.id
    reply = message.reply_to_message

    if reply:
        text = (reply.text or reply.caption or "").strip()
        if not reply.from_user or reply.from_user.is_bot or not text:
            await message.reply("⚠️ Сохранять можно только текстовые сообщения людей.")
            return
        if not message.from_user or message.from_user.id == reply.from_user.id:
            await message.reply("🙅 Свои цитаты сохраняют другие — так честнее.")
            return
        await add_quote(
            chat_id, reply.from_user.id, display_name(reply.from_user), text[:500], message.from_user.id
        )
        await message.reply("📌 Цитата сохранена в золотой фонд чата!")
        return

    quote = await random_quote(chat_id)
    if not quote:
        await message.reply("📭 Цитат пока нет. Ответь на удачную фразу командой /quote, чтобы сохранить.")
        return
    text, author, ts = quote
    date = datetime.fromtimestamp(ts, TZ).strftime("%d.%m.%Y")
    await message.reply(f"💬 <i>«{esc(text)}»</i>\n— <b>{esc(author)}</b>, {date}")


